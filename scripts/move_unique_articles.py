def _wc(html: str) -> int:
    t = re.sub(r"\[/?[^\]]+\]", " ", html)
    t = re.sub(r"<[^>]+>", " ", t)
    return len([w for w in re.split(r"\s+", t) if w])


def _faq(items):
    out = ["<h2>أسئلة عن هذه الخدمة فقط</h2>"]
    for q, a in items:
        out.append(f'<div class="faq-item"><h3>{q}</h3><p>{a}</p></div>')
    return "\n".join(out)


