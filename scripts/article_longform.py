def _essay_for(title: str, pairs: list[tuple[str, str]]) -> str:
    chunks = []
    for key, body in sorted(pairs, key=lambda kv: len(kv[0]), reverse=True):
        if key.lower() in title.lower() or key in title:
            chunks.append(body.strip())
            if len(chunks) >= 2:
                break
    return "\n".join(chunks)


