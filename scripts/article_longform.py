def service_core(title: str) -> str:
    t = re.sub(r"<[^>]+>", "", title).strip()
    t = re.sub(r"^(شركة|فني|سباك)\s+", "", t)
    t = re.sub(r"\s+في\s+\S+\s*$", "", t)
    t = re.sub(r"\s+in\s+.+", "", t, flags=re.I)
    return t.strip() or title


